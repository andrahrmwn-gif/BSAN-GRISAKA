/**
 * Determine Disciplinary Stage based purely on classification Ringan, Sedang, Berat
 */
export function determineDisciplinaryStage(
  currentSeverity: ViolationSeverity,
  totalRingan: number,
  totalSedang: number,
  totalBerat: number
): DisciplinaryStage {
  if (currentSeverity === 'Berat' || totalBerat >= 1) {
    return 'Kepala Sekolah & Tim Penanganan (Pemeriksaan Khusus)';
  }
  if (totalSedang >= 2) {
    return 'Wakasek Kesiswaan (Pemanggilan Ortu & SP)';
  }
  if (currentSeverity === 'Sedang' || totalSedang === 1) {
    return 'Guru BK (Konseling Individu & Kontrak Perilaku)';
  }
  if (totalRingan >= 3) {
    return 'Wali Kelas (Pembinaan Personal & Surat Pernyataan)';
  }
  return 'Guru Mapel / Piket (Teguran Lisan & Buku Kontrol)';
}
